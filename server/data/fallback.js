function cachedDeal({ id, title, appId, sale, normal, rating, badge = 'CACHED SAMPLE' }) {
  const savings = normal > 0 ? Math.max(0, Math.round((1 - sale / normal) * 100)) : 0;
  const slug = title.replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '');

  return {
    id: `fallback-${id}`,
    title,
    store: 'Steam',
    storeId: '1',
    salePrice: sale,
    normalPrice: normal,
    savings,
    rating,
    steamRating: rating,
    steamAppId: String(appId),
    image: `https://cdn.akamai.steamstatic.com/steam/apps/${appId}/header.jpg`,
    dealUrl: `https://store.steampowered.com/app/${appId}/${slug}/`,
    badge,
  };
}

